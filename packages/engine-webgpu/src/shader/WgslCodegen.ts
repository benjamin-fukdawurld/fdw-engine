const textureNames: Record<string, string> = {
  '1d': 'texture_1d',
  '2d': 'texture_2d',
  '2d-array': 'texture_2d_array',
  '3d': 'texture_3d',
  cube: 'texture_cube',
  'cube-array': 'texture_cube_array',
};

const depthTextureNames: Record<string, string> = {
  '2d': 'texture_depth_2d',
  '2d-array': 'texture_depth_2d_array',
  cube: 'texture_depth_cube',
  'cube-array': 'texture_depth_cube_array',
};

const sampledTypes = {
  float: 'f32',
  'unfilterable-float': 'f32',
  sint: 'i32',
  uint: 'u32',
} as const;

export function wgslType(type: ShaderType): string {
  switch (type.kind) {
    case 'scalar':
      return type.scalar;
    case 'vector':
      return `vec${type.size}<${type.scalar}>`;
    case 'matrix':
      return `mat${type.columns}x${type.rows}<${type.scalar}>`;
    case 'texture': {
      if (type.sampleType === 'depth') {
        const name = depthTextureNames[type.dimension];
        if (!name) {
          throw new Error(
            `No WGSL depth texture for dimension ${type.dimension}`,
          );
        }
        return type.multisampled ? 'texture_depth_multisampled_2d' : name;
      }
      const sampled = sampledTypes[type.sampleType];
      return type.multisampled
        ? `texture_multisampled_2d<${sampled}>`
        : `${textureNames[type.dimension]}<${sampled}>`;
    }
    case 'sampler':
      return type.comparison ? 'sampler_comparison' : 'sampler';
    case 'array':
      if (type.length !== undefined) {
        return `array<${wgslType(type.element)}, ${type.length}>`;
      }
      throw new Error('Runtime-sized arrays are not supported yet');
    default:
      throw new Error(
        `${typeToString(type)} is not supported by the WGSL generator`,
      );
  }
}

function floatLiteral(value: number): string {
  const text = String(value);
  return /[.eE]/.test(text) ? text : `${text}.0`;
}

function scalarLiteral(value: number | boolean, scalar: string): string {
  if (typeof value === 'boolean') {
    return String(value);
  }
  switch (scalar) {
    case 'i32':
      return `${value}i`;
    case 'u32':
      return `${value}u`;
    default:
      return floatLiteral(value);
  }
}

function literal(type: ShaderType, value: ConstantValue): string {
  if (type.kind === 'scalar') {
    return scalarLiteral(value as number | boolean, type.scalar);
  }
  if (type.kind === 'vector' || type.kind === 'matrix') {
    const components = (value as readonly number[]).map((component) =>
      scalarLiteral(component, type.scalar),
    );
    return `${wgslType(type)}(${components.join(', ')})`;
  }
  throw new Error(`Cannot write a ${typeToString(type)} literal`);
}

// Texture and sampler values are handles: WGSL does not allow binding them
// to a let, so they are used inline. Arrays of uniform blocks are used
// inline too, indexed in place rather than copied.
const isInline = (type: ShaderType) =>
  type.kind === 'texture' ||
  type.kind === 'sampler' ||
  type.kind === 'array' ||
  type.kind === 'acceleration-structure';

const identifier = (text: string) =>
  text.replace(/[^A-Za-z0-9_]/g, '_').replace(/^_+/, '');

const structName = (name: string) =>
  name.charAt(0).toUpperCase() + name.slice(1);

// Names chosen by the user (uniforms, textures, samplers) are prefixed: they
// can then collide neither with the WGSL keywords and reserved words ('from',
// 'type'…) nor with the builtin functions ('min', 'normalize'…). Uniform
// block names are generated by the compiler and kept as is.
const memberIdentifier = (name: string) => `u_${name}`;

function resourceIdentifier(resource: LogicalBinding): string {
  switch (resource.kind) {
    case 'uniform-block':
      return resource.name;
    case 'texture':
      return `t_${resource.name}`;
    case 'sampler':
      return `s_${resource.name}`;
    case 'storage-buffer':
      return `b_${resource.name}`;
    case 'object-table':
      return resource.name;
    case 'acceleration-structure':
      return `as_${resource.name}`;
  }
}

// The buffers of an acceleration structure (see softwareRayFunctions).
const accelerationBuffers = (name: string) => ({
  top: `${name}_top`,
  bottom: `${name}_bottom`,
});

// The second buffer of an object table: the row of each instance.
const instancesIdentifier = (table: string) => `${table}Instances`;

const builtinParameters = {
  'vertex-index': {
    name: 'vertexIndex',
    declaration: '@builtin(vertex_index) vertexIndex: u32',
  },
  'instance-index': {
    name: 'instanceIndex',
    declaration: '@builtin(instance_index) instanceIndex: u32',
  },
  'front-facing': {
    name: 'frontFacing',
    declaration: '@builtin(front_facing) frontFacing: bool',
  },
  'global-invocation-id': {
    name: 'globalInvocationId',
    declaration: '@builtin(global_invocation_id) globalInvocationId: vec3<u32>',
  },
  'local-invocation-id': {
    name: 'localInvocationId',
    declaration: '@builtin(local_invocation_id) localInvocationId: vec3<u32>',
  },
  'workgroup-id': {
    name: 'workgroupId',
    declaration: '@builtin(workgroup_id) workgroupId: vec3<u32>',
  },
  'num-workgroups': {
    name: 'numWorkgroups',
    declaration: '@builtin(num_workgroups) numWorkgroups: vec3<u32>',
  },
} as const;

function stageVariable(variable: IrStageVariable): string {
  const attributes = variable.builtin
    ? `@builtin(${variable.builtin})`
    : `@location(${variable.location})${
        variable.interpolation === 'flat' ? ' @interpolate(flat)' : ''
      }`;
  return `  ${attributes} ${variable.name}: ${wgslType(variable.type)},`;
}

interface BodyState {
  readonly lines: string[];
  readonly expressions: Map<number, string>;
  readonly builtins: Set<string>;
  // The functions the code calls besides those of its resources (the
  // traversals with alpha test), by name: shared by the stages.
  readonly helpers: Map<string, string>;
}

const valueName = (instruction: IrInstruction) =>
  `v${instruction.id}${
    instruction.name ? `_${identifier(instruction.name)}` : ''
  }`;

function emitBody(
  entryPoint: IrEntryPoint,
  resources: ReadonlyMap<string, string>,
  helpers: Map<string, string>,
): BodyState {
  const state: BodyState = {
    lines: [],
    expressions: new Map(),
    builtins: new Set(),
    helpers,
  };
  const { active } = entryPoint;
  if (active) {
    // The threads out of the guard stop once it is known.
    emitInstructions(entryPoint.body.slice(0, active.after), resources, state, '  ');
    state.lines.push(
      `  if (!(${state.expressions.get(active.value)})) {`,
      '    return;',
      '  }',
    );
    emitInstructions(entryPoint.body.slice(active.after), resources, state, '  ');
  } else {
    emitInstructions(entryPoint.body, resources, state, '  ');
  }
  return state;
}

function emitInstructions(
  body: readonly IrInstruction[],
  resources: ReadonlyMap<string, string>,
  state: BodyState,
  indent: string,
): void {
  const { lines, expressions, builtins } = state;
  const arg = (instruction: IrInstruction, index: number) =>
    expressions.get(instruction.args[index]) as string;
  const args = (instruction: IrInstruction) =>
    instruction.args.map((_, i) => arg(instruction, i)).join(', ');

  for (const instruction of body) {
    const { op, type } = instruction;
    let expression: string;
    switch (op.kind) {
      case 'loop-sum': {
        const sum = valueName(instruction);
        const index = `v${op.index}`;
        const count = arg(instruction, 0);
        lines.push(
          `${indent}var ${sum}: ${wgslType(type)} = ${wgslType(type)}();`,
          `${indent}for (var ${index}: u32 = 0u; ${index} < ${count}; ${index} = ${index} + 1u) {`,
        );
        expressions.set(op.index, index);
        emitInstructions(op.body, resources, state, `${indent}  `);
        lines.push(
          `${indent}  ${sum} = ${sum} + ${expressions.get(op.result)};`,
          `${indent}}`,
        );
        expressions.set(instruction.id, sum);
        continue;
      }
      case 'loop-fold': {
        // The state lives in a variable, read by the body as it is at the
        // start of the iteration and written at its end.
        const fold = valueName(instruction);
        const index = `v${op.index}`;
        lines.push(
          `${indent}var ${fold}: ${wgslType(type)} = ${arg(instruction, 1)};`,
          `${indent}for (var ${index}: u32 = 0u; ${index} < ${arg(
            instruction,
            0,
          )}; ${index} = ${index} + 1u) {`,
        );
        expressions.set(op.index, index);
        expressions.set(op.state, fold);
        emitInstructions(op.body, resources, state, `${indent}  `);
        lines.push(
          `${indent}  ${fold} = ${expressions.get(op.result)};`,
          `${indent}}`,
        );
        expressions.set(instruction.id, fold);
        continue;
      }
      case 'index':
        expression = `${arg(instruction, 0)}[${arg(instruction, 1)}]`;
        break;
      case 'array-length':
        // Storage arrays are used inline: their expression is the variable.
        expression = `arrayLength(&${arg(instruction, 0)})`;
        break;
      case 'bitcast':
        expression = `bitcast<${wgslType(type)}>(${arg(instruction, 0)})`;
        break;
      case 'ray-query': {
        // The expression of the structure is its identifier: as_<name>.
        const binding = arg(instruction, 0).replace(/^as_/, '');
        const [, origin, direction, tMin, tMax, mask, instances, geometry] =
          instruction.args.map((id) => expressions.get(id) as string);
        const alphaTest = op.alphaTest === true;
        const name = traceFunctionName(binding, alphaTest);
        if (alphaTest && !state.helpers.has(name)) {
          state.helpers.set(
            name,
            softwareRayFunctions(binding, accelerationBuffers(arg(instruction, 0)), {
              instances,
              geometry,
            }),
          );
        }
        expression = `${name}(${origin}, ${direction}, ${tMin}, ${tMax}, ${mask}, ${
          op.mode === 'any'
        })`;
        break;
      }
      case 'constant':
        expression = literal(type, op.value);
        break;
      case 'load-input':
        expression = `in.${op.input}`;
        break;
      case 'load-builtin':
        if (op.builtin === 'object-index') {
          // The row of the instance: instance_index includes firstInstance.
          builtins.add('instance-index');
          expression = `${instancesIdentifier(objectTable(resources))}[${
            builtinParameters['instance-index'].name
          }]`;
        } else if (op.builtin === 'frag-coord') {
          // In a fragment shader, the position builtin is the fragment
          // coordinate.
          expression = 'in.clipPosition';
        } else {
          builtins.add(op.builtin);
          expression = builtinParameters[op.builtin].name;
        }
        break;
      case 'load-resource': {
        const binding = resources.get(op.binding);
        if (!binding) {
          throw new Error(`Binding "${op.binding}" is not in the layout`);
        }
        expression = op.member
          ? `${binding}.${memberIdentifier(op.member)}`
          : binding;
        break;
      }
      case 'load-object':
        expression = `${objectTable(resources)}[${arg(
          instruction,
          0,
        )}].${memberIdentifier(op.member)}`;
        break;
      case 'binary':
        // The amount of a shift is unsigned in WGSL.
        expression =
          (op.operator === '<<' || op.operator === '>>') &&
          (type.kind === 'scalar' || type.kind === 'vector') &&
          type.scalar === 'i32'
            ? `${arg(instruction, 0)} ${op.operator} ${wgslType(
                type.kind === 'scalar'
                  ? { kind: 'scalar', scalar: 'u32' }
                  : { kind: 'vector', size: type.size, scalar: 'u32' },
              )}(${arg(instruction, 1)})`
            : `${arg(instruction, 0)} ${op.operator} ${arg(instruction, 1)}`;
        break;
      case 'compare':
        // Comparisons are component-wise for vectors in WGSL.
        expression = `${arg(instruction, 0)} ${op.operator} ${arg(
          instruction,
          1,
        )}`;
        break;
      case 'intrinsic':
        expression = `${op.name}(${args(instruction)})`;
        break;
      case 'select':
        expression = `select(${args(instruction)})`;
        break;
      case 'sample':
        expression = `textureSample(${args(instruction)})`;
        break;
      case 'sample-level':
        expression = `textureSampleLevel(${args(instruction)})`;
        break;
      case 'sample-compare':
        expression = `textureSampleCompareLevel(${args(instruction)})`;
        break;
      case 'texture-load':
        expression = `textureLoad(${args(instruction)})`;
        break;
      case 'construct':
      case 'convert':
        expression = `${wgslType(type)}(${args(instruction)})`;
        break;
      case 'swizzle':
        expression = `${arg(instruction, 0)}.${op.components}`;
        break;
    }

    if (isInline(type)) {
      expressions.set(instruction.id, expression);
      continue;
    }
    const name = valueName(instruction);
    const comment = instruction.sourceNode
      ? ` // #${instruction.sourceNode}`
      : '';
    lines.push(
      `${indent}let ${name}: ${wgslType(type)} = ${expression};${comment}`,
    );
    expressions.set(instruction.id, name);
  }
}

// The key of the object table in the identifiers of the resources.
const ObjectTableKey = '#object-table';

// The identifier of the object table of the layout.
function objectTable(resources: ReadonlyMap<string, string>): string {
  const table = resources.get(ObjectTableKey);
  if (!table) {
    throw new Error('The layout has no object table');
  }
  return table;
}

// Declares the resources of the layout; returns their identifiers in the
// code, by binding name.
function declareResources(
  layout: PhysicalProgramLayout,
  sections: string[],
): Map<string, string> {
  const resources = new Map<string, string>();
  for (const group of layout.groups) {
    for (const { binding, resource } of group.bindings) {
      const location = `@group(${group.index}) @binding(${binding})`;
      const name = resourceIdentifier(resource);
      resources.set(resource.name, name);
      if (resource.kind === 'uniform-block') {
        const struct = structName(resource.name);
        sections.push(
          [
            `struct ${struct} {`,
            ...resource.members.map(
              (member) =>
                `  ${memberIdentifier(member.name)}: ${wgslType(member.type)},`,
            ),
            '};',
            `${location} var<uniform> ${name}: ${struct};`,
          ].join('\n'),
        );
      } else if (resource.kind === 'object-table') {
        // The rows, then the row of each instance, at the next binding.
        const struct = `${structName(resource.name)}Row`;
        resources.set(ObjectTableKey, name);
        sections.push(
          [
            `struct ${struct} {`,
            ...resource.members.map(
              (member) =>
                `  ${memberIdentifier(member.name)}: ${wgslType(member.type)},`,
            ),
            '};',
            `${location} var<storage, read> ${name}: array<${struct}>;`,
            `@group(${group.index}) @binding(${
              binding + 1
            }) var<storage, read> ${instancesIdentifier(name)}: array<u32>;`,
          ].join('\n'),
        );
      } else if (resource.kind === 'acceleration-structure') {
        // Two storage buffers, then the functions tracing rays in them.
        const buffers = accelerationBuffers(name);
        sections.push(
          [buffers.top, buffers.bottom]
            .map(
              (buffer, offset) =>
                `@group(${group.index}) @binding(${
                  binding + offset
                }) var<storage, read> ${buffer}: array<vec4<f32>>;`,
            )
            .join('\n'),
          softwareRayFunctions(resource.name, buffers),
        );
      } else if (resource.kind === 'texture') {
        sections.push(`${location} var ${name}: ${wgslType(resource.type)};`);
      } else if (resource.kind === 'storage-buffer') {
        sections.push(
          `${location} var<storage, ${
            resource.access === 'read-write' ? 'read_write' : 'read'
          }> ${name}: array<${wgslType(resource.type.element)}>;`,
        );
      } else {
        sections.push(
          `${location} var ${name}: ${
            resource.comparison ? 'sampler_comparison' : 'sampler'
          };`,
        );
      }
    }
  }
  return resources;
}

// A compute stage: the body, then the writes, in order.
function emitCompute(
  compute: IrEntryPoint,
  resources: ReadonlyMap<string, string>,
  helpers: Map<string, string>,
): string {
  const body = emitBody(compute, resources, helpers);
  const [x, y, z] = compute.workgroupSize ?? [1, 1, 1];
  const writes = (compute.writes ?? []).flatMap((write) => {
    const target = resources.get(write.resource);
    if (!target) {
      throw new Error(`Binding "${write.resource}" is not in the layout`);
    }
    const statement = `${target}[${body.expressions.get(
      write.index,
    )}] = ${body.expressions.get(write.value)};`;
    return write.condition === undefined
      ? [`  ${statement}`]
      : [
          `  if (${body.expressions.get(write.condition)}) {`,
          `    ${statement}`,
          '  }',
        ];
  });
  const parameters = [...body.builtins].map(
    (builtin) =>
      builtinParameters[builtin as keyof typeof builtinParameters].declaration,
  );
  return [
    `@compute @workgroup_size(${x}, ${y}, ${z})`,
    `fn cs_main(${parameters.join(', ')}) {`,
    ...body.lines,
    ...writes,
    '}',
  ].join('\n');
}

// Generates a WGSL module with a vs_main and an fs_main entry point, or a
// cs_main one for a compute stage.
export class WgslCodegen implements ShaderCodegen {
  readonly language = 'wgsl' as const;

  emit(module: ShaderModuleIR, layout: PhysicalProgramLayout): ShaderSources {
    const sections: string[] = [
      `// Generated from graph "${module.name}". Do not edit.`,
    ];
    const resources = declareResources(layout, sections);
    const helpers = new Map<string, string>();

    const compute = module.entryPoints.find(
      (entryPoint) => entryPoint.stage === 'compute',
    );
    if (compute) {
      const main = emitCompute(compute, resources, helpers);
      sections.push(...helpers.values(), main);
      return {
        kind: 'single-module',
        code: `${sections.join('\n\n')}\n`,
        entryPoints: { compute: 'cs_main' },
      };
    }

    const vertex = module.entryPoints.find(
      (entryPoint) => entryPoint.stage === 'vertex',
    );
    const fragment = module.entryPoints.find(
      (entryPoint) => entryPoint.stage === 'fragment',
    );
    if (!vertex || !fragment) {
      throw new Error(
        'A program needs a vertex and a fragment entry point, or a compute one',
      );
    }
    if (vertex.inputs.length > 0) {
      sections.push(
        [
          'struct VertexInput {',
          ...vertex.inputs.map(stageVariable),
          '};',
        ].join('\n'),
      );
    }
    sections.push(
      ['struct Varyings {', ...vertex.outputs.map(stageVariable), '};'].join(
        '\n',
      ),
    );

    const vertexBody = emitBody(vertex, resources, helpers);
    const vertexParameters = [
      ...(vertex.inputs.length > 0 ? ['in: VertexInput'] : []),
      ...[...vertexBody.builtins].map(
        (builtin) =>
          builtinParameters[builtin as keyof typeof builtinParameters]
            .declaration,
      ),
    ];
    sections.push(
      [
        '@vertex',
        `fn vs_main(${vertexParameters.join(', ')}) -> Varyings {`,
        ...vertexBody.lines,
        '  var out: Varyings;',
        ...vertex.outputs.map(
          (output) =>
            `  out.${output.name} = ${vertexBody.expressions.get(
              vertex.results[output.name],
            )};`,
        ),
        '  return out;',
        '}',
      ].join('\n'),
    );

    const fragmentBody = emitBody(fragment, resources, helpers);
    const fragmentParameters = [
      'in: Varyings',
      ...[...fragmentBody.builtins].map(
        (builtin) =>
          builtinParameters[builtin as keyof typeof builtinParameters]
            .declaration,
      ),
    ];
    // Depth-only programs have no color; several targets go in a structure.
    const color =
      fragment.outputs.length === 1
        ? (fragment.outputs[0] as IrStageVariable)
        : undefined;
    const targets = fragment.outputs.length > 1 ? fragment.outputs : [];
    if (targets.length > 0) {
      sections.push(
        [
          'struct FragmentOutputs {',
          ...targets.map(
            (target) =>
              `  @location(${target.location}) o_${identifier(
                target.name,
              )}: ${wgslType(target.type)},`,
          ),
          '}',
        ].join('\n'),
      );
    }
    sections.push(
      [
        '@fragment',
        `fn fs_main(${fragmentParameters.join(', ')})${
          color
            ? ` -> @location(${color.location}) ${wgslType(color.type)}`
            : targets.length > 0
              ? ' -> FragmentOutputs'
              : ''
        } {`,
        ...fragmentBody.lines,
        // After the whole body: every texture sample has run.
        ...(fragment.results['discard'] !== undefined
          ? [
              `  if (${fragmentBody.expressions.get(
                fragment.results['discard'],
              )}) {`,
              '    discard;',
              '  }',
            ]
          : []),
        ...(color
          ? [
              `  return ${fragmentBody.expressions.get(
                fragment.results[color.name],
              )};`,
            ]
          : []),
        ...(targets.length > 0
          ? [
              '  var targets: FragmentOutputs;',
              ...targets.map(
                (target) =>
                  `  targets.o_${identifier(
                    target.name,
                  )} = ${fragmentBody.expressions.get(
                    fragment.results[target.name],
                  )};`,
              ),
              '  return targets;',
            ]
          : []),
        '}',
      ].join('\n'),
    );

    sections.push(...helpers.values());
    return {
      kind: 'single-module',
      code: `${sections.join('\n\n')}\n`,
      entryPoints: { vertex: 'vs_main', fragment: 'fs_main' },
    };
  }
}
